#!/usr/bin/env node
/* Build index.html from src/: concatenate the styles and scripts in the order below.
   No transpiling, no minifying: the output is the same single file the game always was.

     node build.js           write index.html and www/ (the folder to publish)
     node build.js --check   fail if index.html is out of date with src/

   Both syntax-check the script. Order matters: the scripts are slices of one
   IIFE (main-open ... main-close) with the pixel scene as an inner IIFE
   (scene-open ... scene-close), so they share one scope. */
"use strict";
var fs = require("fs"), path = require("path"), vm = require("vm");

var STYLES = ["fonts", "tokens", "base", "layout", "controls", "panels", "team", "trees", "calendar", "windows", "scene", "shared"];
var SCRIPTS = [
  "main-open",
  /* engine: no DOM, no storage. Talks to the UI only through emit() (engine/events.js) */
  "data/types", "data/balance", "data/catalog", "data/people", "data/calendar", "data/trees",
  "engine/events", "state",
  "engine/helpers", "engine/calendar", "engine/shifts", "engine/money", "engine/orders", "engine/actions",
  "engine/missions", "engine/longterm",
  /* engine UI: panels built once and refreshed every tick */
  "ui/dom", "ui/overlay", "ui/windows", "ui/build", "ui/update",
  /* the browser app: storage, the 100 ms loop, boot */
  "app/storage", "app/loop", "app/start", "app/pwa",
  "scene/scene-open",
  "scene/sprites", "scene/stages", "scene/customers", "scene/render", "scene/tutorial", "scene/layout",
  "scene/ui/icons", "scene/ui/effects", "scene/ui/tabs", "scene/ui/rows", "scene/ui/expansion", "scene/ui/trees",
  "scene/ui/stock", "scene/ui/missions", "scene/ui/bank", "scene/ui/decor", "scene/ui/venue", "scene/ui/refresh",
  "scene/scene-close",
  "main-close"
];
/* the files that make up the headless engine (tools/engine.js runs them in Node) */
var ENGINE = SCRIPTS.filter(function (s) { return /^(data|engine)\//.test(s) || s === "state"; });
var BANNER = "<!-- Generated by build.js from src/. Edit the files in src/, then run: node build.js -->\n";

var ROOT = __dirname, SRC = path.join(ROOT, "src"), OUT = path.join(ROOT, "index.html");
function read(f) { return fs.readFileSync(path.join(SRC, f), "utf8"); }
function cat(dir, names, ext) { return names.map(function (n) { return read(dir + "/" + n + ext); }).join(""); }

/* the browser silently drops everything after a stray brace: check each stylesheet's nesting first */
function checkCss(name, text) {
  var depth = 0, paren = 0, quote = null, line = 1;
  for (var i = 0; i < text.length; i++) {
    var c = text[i];
    if (c === "\n") line++;
    if (quote) { if (c === quote && text[i - 1] !== "\\") quote = null; continue; }
    if (c === "/" && text[i + 1] === "*") { var end = text.indexOf("*/", i + 2); line += text.slice(i, end).split("\n").length - 1; i = end + 1; continue; }
    if (c === '"' || c === "'") quote = c;
    else if (c === "(") paren++;
    else if (c === ")") paren--;
    else if (c === "{") depth++;
    else if (c === "}" && --depth < 0) return name + ":" + line + ": unexpected }";
    if (paren < 0) return name + ":" + line + ": unexpected )";
  }
  return depth ? name + ": " + depth + " unclosed {" : paren ? name + ": unclosed (" : quote ? name + ": unclosed string" : null;
}
STYLES.forEach(function (n) {
  var err = checkCss("src/styles/" + n + ".css", read("styles/" + n + ".css"));
  if (err) { console.error("CSS error: " + err); process.exit(1); }
});
var css = cat("styles", STYLES, ".css"), js = cat("js", SCRIPTS, ".js");
try { new vm.Script(js, { filename: "index.html <script>" }); }
catch (e) { console.error("Syntax error in the built script:\n" + e.stack); process.exit(1); }

var tpl = read("index.html");
["@@styles\n", "@@script\n"].forEach(function (m) {
  if (tpl.split(m).length !== 2) { console.error("src/index.html must contain " + m.trim() + " exactly once"); process.exit(1); }
});
var html = tpl.replace("@@styles\n", function () { return css; }).replace("@@script\n", function () { return js; });
html = html.replace(/^(<!DOCTYPE html>\n)/, "$1" + BANNER);
var MANIFEST = "<!--@@manifest-->";   /* only the published page (www/) has a manifest; index.html opened from disk does not */
var wwwHtml = html.replace(MANIFEST, '<link rel="manifest" href="manifest.webmanifest">');
html = html.replace(MANIFEST + "\n", "");

module.exports = { ENGINE: ENGINE, engineSource: function () { return cat("js", ENGINE, ".js"); } };
if (require.main !== module) return;

if (process.argv.indexOf("--check") >= 0) {
  var cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== html) { console.error("index.html is out of date: run node build.js"); process.exit(1); }
  console.log("index.html is up to date, script syntax ok");
} else {
  fs.writeFileSync(OUT, html);
  console.log("index.html written: " + html.split("\n").length + " lines, " + SCRIPTS.length + " scripts, " + STYLES.length + " stylesheets");
  buildWww(wwwHtml);
}

/* www/: what gets published (GitHub Pages, or an app shell's web folder): the page, its assets, the manifest
   and a service worker whose version is a hash of everything else, so every release refreshes the cache */
function buildWww(page) {
  var crypto = require("crypto"), WWW = path.join(ROOT, "www"), ASSETS = ["fonts", "audio", "icons"];
  fs.rmSync(WWW, { recursive: true, force: true });
  fs.mkdirSync(WWW);
  fs.writeFileSync(path.join(WWW, "index.html"), page);
  ASSETS.forEach(function (d) { fs.cpSync(path.join(ROOT, d), path.join(WWW, d), { recursive: true }); });
  fs.copyFileSync(path.join(SRC, "pwa", "manifest.webmanifest"), path.join(WWW, "manifest.webmanifest"));
  var files = ["index.html", "manifest.webmanifest"];
  ASSETS.forEach(function (d) { fs.readdirSync(path.join(WWW, d)).sort().forEach(function (f) { files.push(d + "/" + f); }); });
  var hash = crypto.createHash("sha256");
  files.forEach(function (f) { hash.update(f); hash.update(fs.readFileSync(path.join(WWW, f))); });
  var shell = ["./"].concat(files.filter(function (f) { return !/^audio\/|\.txt$/.test(f); }));   /* music is cached when it first plays */
  var sw = read("pwa/sw.js").replace("__VERSION__", hash.digest("hex").slice(0, 12)).replace("__SHELL__", JSON.stringify(shell));
  fs.writeFileSync(path.join(WWW, "sw.js"), sw);
  console.log("www/ written: " + files.length + " files + sw.js");
}
